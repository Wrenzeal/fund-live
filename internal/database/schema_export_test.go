package database

import (
	"bytes"
	"os"
	"strings"
	"testing"
)

func TestFreshSchemaMatchesDeploymentArtifact(t *testing.T) {
	var generated bytes.Buffer
	if err := WriteFreshSchema(&generated); err != nil {
		t.Fatal(err)
	}
	artifact, err := os.ReadFile("../../scripts/sql/fundlive-schema.sql")
	if err != nil {
		t.Fatal(err)
	}
	if strings.ReplaceAll(string(artifact), "\r\n", "\n") != generated.String() {
		t.Fatal("deployment SQL is stale; run go run ./cmd/export-db-schema --output scripts/sql/fundlive-schema.sql")
	}
}

func TestFreshSchemaIsGuardedAndTransactional(t *testing.T) {
	var generated bytes.Buffer
	if err := WriteFreshSchema(&generated); err != nil {
		t.Fatal(err)
	}
	sql := generated.String()
	guard := strings.Index(sql, "RAISE EXCEPTION 'Database contains existing relations")
	create := strings.Index(sql, "CREATE TABLE schema_migrations")
	if guard < 0 || create < guard {
		t.Fatal("schema creation must follow the empty database guard")
	}
	if !strings.Contains(sql, "current_database() <> 'fundlive' OR current_user <> 'fundlive'") {
		t.Fatal("database and role must be checked before initialization")
	}
	if !strings.Contains(sql[:guard], "n.nspname !~ '^pg_'") {
		t.Fatal("only PostgreSQL's literal pg_ schema prefix may be excluded from the empty database check")
	}
	if !strings.HasSuffix(sql, "COMMIT;\n") || !strings.Contains(sql[:guard], "BEGIN;\n") {
		t.Fatal("bootstrap must be a single transaction")
	}
	if records := strings.Count(sql, "INSERT INTO schema_migrations (id)"); records != len(managedMigrations) {
		t.Fatalf("migration records = %d, want %d", records, len(managedMigrations))
	}
}

type failingSchemaWriter struct{}

func (failingSchemaWriter) Write([]byte) (int, error) { return 0, os.ErrPermission }

func TestFreshSchemaPropagatesOutputErrors(t *testing.T) {
	if err := WriteFreshSchema(failingSchemaWriter{}); err != os.ErrPermission {
		t.Fatalf("write error = %v, want %v", err, os.ErrPermission)
	}
}
