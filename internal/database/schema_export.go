package database

import (
	"fmt"
	"io"
	"strings"
)

// WriteFreshSchema exports the managed migrations for an empty FundLive database.
func WriteFreshSchema(w io.Writer) error {
	var sql strings.Builder
	sql.WriteString(`-- Generated by go run ./cmd/export-db-schema; do not edit manually.
-- Run as fundlive against a new, empty fundlive database with psql ON_ERROR_STOP=1.
-- This file initializes tables and migration records, not user or market data.
BEGIN;
SET LOCAL search_path = public;
SELECT pg_advisory_xact_lock(hashtext(current_database()), hashtext('fundlive-schema-bootstrap'));

DO $fundlive_bootstrap$
BEGIN
    IF current_database() <> 'fundlive' OR current_user <> 'fundlive' THEN
        RAISE EXCEPTION 'Expected database fundlive and role fundlive; refusing initialization';
    END IF;
    IF EXISTS (
        SELECT 1
        FROM pg_class c
        JOIN pg_namespace n ON n.oid = c.relnamespace
        WHERE n.nspname !~ '^pg_'
          AND n.nspname <> 'information_schema'
          AND c.relkind IN ('r', 'p', 'v', 'm', 'S', 'f')
    ) THEN
        RAISE EXCEPTION 'Database contains existing relations; fresh initialization refused';
    END IF;
END;
$fundlive_bootstrap$;

CREATE TABLE schema_migrations (
    id varchar(128) PRIMARY KEY,
    applied_at timestamptz NOT NULL DEFAULT now()
);

`)
	for _, migration := range managedMigrations {
		fmt.Fprintf(&sql, "-- Migration: %s\n", migration.ID)
		for _, statement := range migration.Statements {
			sql.WriteString(strings.TrimRight(strings.TrimSpace(statement), ";"))
			sql.WriteString(";\n\n")
		}
		id := strings.ReplaceAll(migration.ID, "'", "''")
		fmt.Fprintf(&sql, "INSERT INTO schema_migrations (id) VALUES ('%s');\n\n", id)
	}
	sql.WriteString("COMMIT;\n")
	result := sql.String()
	n, err := io.WriteString(w, result)
	if err == nil && n != len(result) {
		return io.ErrShortWrite
	}
	return err
}
